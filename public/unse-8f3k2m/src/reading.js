function child(n) {
  if (n >= 3) return '자식의 기운이 두텁습니다. 아이가 생기고 나서 흐름이 배가 되는 자리이고, 자식에게서 오는 기쁨과 걱정이 함께 큽니다. 어릴 때 교육에 들인 것이 그대로 돌아옵니다.';
  if (n === 2) return '자식과의 인연이 순합니다. 크게 애태우지 않고 키우게 되며 자라서도 부모를 살핍니다. 중년 초반에 한 번 마음 쓸 일이 있으나 넘어갈 만한 정도입니다.';
  if (n === 1) return '자식이 늦거나 하나에 집중됩니다. 수가 적은 대신 정이 깊고 그만큼 기대도 커지기 쉬우니, 그 무게를 아이에게 그대로 얹지 않도록 살펴야 합니다.';
  return '자식보다 자기 일이 먼저 섭니다. 늦게 두거나 적게 두는 편이고 그 자리를 일이나 배움이 대신 채웁니다. 없는 것이 아니라 순서가 다른 것입니다.';
}

function spouse(n, isMale) {
  const who = isMale ? '배우자' : '남편';
  if (n >= 3) return `${who}의 자리가 여럿으로 잡힙니다. 인연이 늦게 정해지거나 한 번 크게 굽이치는 편이고, 정해진 뒤에는 오히려 안정됩니다. 고르는 시기를 서두르지 않는 편이 낫습니다.`;
  if (n === 2) return '보통 일반의 가정을 꾸립니다. 바깥 역할은 무리 없이 해내지만 집 안보다 밖에 마음이 더 쏠려서, 부부지정이 모자란 듯 느껴질 때가 옵니다. 역할을 못 하는 것은 아니니 익숙한 정을 쌓아가는 사이가 됩니다.';
  if (n === 1) return '한 사람에게 오래 매입니다. 인연이 자주 바뀌지 않고 한번 정하면 잘 흔들리지 않습니다. 그만큼 상대에 따라 삶의 결이 크게 달라지니 고를 때 신중해야 합니다.';
  return `혼자서도 온전합니다. 인연이 늦거나 담백하게 이어지며, 붙어 있는 시간보다 각자의 자리를 지키는 쪽이 서로 편한 사이가 됩니다.`;
}

