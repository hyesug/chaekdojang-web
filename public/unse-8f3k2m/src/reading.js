/* ── 확신도 ─────────────────────────────────────────────────
   근거 없이 단정하는 글이 제일 나쁘다. 합의가 낮으면 물러선다. */
export function certainty(ratio = 50) {
  if (ratio >= 62) return { level: 'high', hedge: '' };
  if (ratio >= 42) return { level: 'mid', hedge: '' };
  return { level: 'low',
    hedge: ' 다만 이 대목은 보는 자리마다 달리 읽히니 참고로만 두세요.' };
}

