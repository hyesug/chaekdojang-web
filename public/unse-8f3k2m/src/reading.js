function hiddenElsewhere(chart, dayStem, group) {
  for (const p of Object.values(chart.pillars)) {
    if (!p) continue;
    for (const st of HIDDEN_STEMS[p.branch]) {
      if (st === MAIN_HIDDEN[p.branch]) continue;
      if (TEN_GOD_GROUP[tenGod(dayStem, st)] === group) return true;
    }
  }
  return false;
}

