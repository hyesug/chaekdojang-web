  el.pct.forEach((v, i) => {
    if (missing.has(i) || v < 3) { lines.push(NO_ELEMENT[i]); weight += 2; }
    else if (v >= 35) { lines.push(TOO_MUCH[i]); weight += 2; }
  });

  for (const g of GOD_GROUPS) {
    const n = gods.groups[g] ?? 0;
    if (n === 0) { lines.push(GOD_NONE[g]); weight += 2; }
    else if (n >= 4) { lines.push(GOD_TOO_MUCH[g]); weight += 2; }
  }

  const level = weight >= 6 ? 'strong' : weight >= 2 ? 'some' : 'even';
  const head =
    level === 'strong'
