/**
 * 열다섯을 돌리는 이유가 여기 있다.
 * 가운데 있는 열세 개는 굳이 늘어놓지 않는다. 읽는 사람에게 필요한 건
 * '여럿이 동의하는 것'과 '의견이 갈리는 양 끝'이지 전부가 아니다.
 */
export function consensusReading(r, block) {
  const s = r.synthesis;
  const out = {};

  const agreed = (s.sharedTags ?? []).filter((t) => t.count >= 2).slice(0, 4);
  if (agreed.length) {
    const top = agreed[0];
    const rest = agreed.slice(1);
    const phrase = (t) => TAG_MEANING[t.word] ?? t.word;

    out.공통 = {
      text:
        `계산 방식이 전혀 다른 ${top.count}곳이 나란히 짚는 것이 있습니다. ` +
        `${phrase(top)}이라는 점입니다. ` +
        (rest.length
          ? `여기에 ${rest.map(phrase).join(', ')}이라는 결이 겹쳐집니다. `
          : '') +
        `한 곳만 말했다면 흘려들어도 되지만 서로 다른 길로 걸어와 같은 자리를 ` +
        `가리킨 것이라, 이 대목은 회원님을 설명하는 뼈대로 보셔도 됩니다.`,
      sources: top.from,
    };
  } else {
    out.공통 = {
      text: '여러 갈래가 겹치는 자리가 없습니다. 어느 하나로 잘라 말하기 어려운 구성이라는 뜻이니, 한 가지를 정답으로 두지 마시고 상황에 따라 다른 얼굴이 나온다고 보시는 편이 맞습니다.',
      sources: [],
    };
  }

  // 갈림 — 체계 원문을 그대로 옮기면 용어가 튀어나온다. 점수와 영역만 보고 푼다.
  const voices = (block?.results ?? [])
    .filter((x) => x.areas?.총운 != null)
    .slice()
    .sort((a2, b2) => b2.areas.총운 - a2.areas.총운);

  if (voices.length >= 3) {
    const hi = voices[0], lo = voices[voices.length - 1];
    const gap = hi.areas.총운 - lo.areas.총운;
    const areaOf = (v, dir) => {
      const list = AREAS.filter((a2) => v.areas?.[a2] != null);
      if (!list.length) return null;
      return list.sort((x, y) =>
        dir > 0 ? v.areas[y] - v.areas[x] : v.areas[x] - v.areas[y])[0];
    };
    // '총운'에서 '운'만 떼면 '총 쪽'이 된다. 영역마다 부르는 말을 따로 둔다.
    const AREA_WORD = {
      총운: '전반', 애정운: '사람 관계', 금전운: '재물',
      직장운: '일과 자리', 학업운: '배움', 건강운: '몸',
    };
    const say2 = (a2) => AREA_WORD[a2] ?? a2;
    const hiArea = areaOf(hi, 1), loArea = areaOf(lo, -1);

    out.갈림 = {
      text:
        `이 시기를 보는 눈이 갈립니다. 한쪽에서는 밀고 나가도 좋은 때로 봅니다` +
        (hiArea ? ` — 특히 ${say2(hiArea)} 쪽을 밝게 봅니다` : '') +
        `. 다른 쪽에서는 벌이기보다 마무리에 어울리는 자리로 봅니다` +
        (loArea ? ` — ${say2(loArea)} 쪽을 특히 조심스럽게 봅니다` : '') +
        `. ` +
        (gap >= 30
          ? '두 쪽의 거리가 멀어서 어느 한쪽만 믿기 어렵습니다. 새로 벌이는 일은 작게 시작하고, 이미 벌여둔 것은 정리해 두는 절충이 현실적입니다.'
          : '거리가 크지는 않으니, 큰 방향은 밀고 가되 위에서 조심하라고 한 쪽만 따로 챙기시면 됩니다.'),
      sources: [hi.name, lo.name],
    };
  }
  return out;
}
