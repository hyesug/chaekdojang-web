/**
 * reading.js — 사람이 읽는 리딩
 *
 * 여태 화면은 "어느 체계가 무엇을 말한다"를 보여줬다. 그런데 십신이니
 * 아쉬타쿠타니 하는 말은 일반인에게 아무 뜻이 없다. 돈 내고 사주를 보러
 * 가면 그런 걸 늘어놓지 않는다. 그냥 내 이야기를 해준다.
 *
 * 그래서 이 파일은 열다섯 체계의 계산 결과를 용어 없는 글로 바꾼다.
 * 본문에 체계 이름은 나오지 않는다. 다만 괄호로 근거는 밝힌다.
 *
 * 열다섯을 돌린 값은 여기서 두 가지로 쓰인다.
 *   1. 합의가 높으면 단정해서 쓰고, 갈리면 갈린다고 쓴다 (말투의 확신도)
 *   2. 항목마다 그 주제를 보는 체계가 앞에 온다 (괄호 안의 순서)
 * 그게 열다섯을 다 돌려서 얻는 것이다.
 */

