const tagWord = (t) => TAG_MEANING[t]?.[0] ?? t;
const tagShows = (t) => TAG_MEANING[t]?.[1] ?? null;

/**
 * 열다섯을 돌리는 이유가 여기 있다.
 * 가운데 있는 열세 개는 굳이 늘어놓지 않는다. 읽는 사람에게 필요한 건
 * '여럿이 동의하는 것'과 '의견이 갈리는 양 끝'이지 전부가 아니다.
 */
export function consensusReading(r, block) {
  const s = r.synthesis;
  const out = {};

  const agreed = (s.sharedTags ?? []).filter((t) => t.count >= 2).slice(0, 3);
  if (agreed.length) {
    const [first, second] = agreed;
    const parts = [
      `계산 방식이 전혀 다른 ${first.count}곳이 나란히 짚는 것이 있습니다. ` +
      `${j(tagWord(first.word), '이')} 이 사람의 바탕입니다.`,
    ];
    if (tagShows(first.word)) parts.push(`${tagShows(first.word)}.`);
    if (second) {
      parts.push(`여기에 ${tagWord(second.word)}이라는 결이 겹칩니다.`);
      if (tagShows(second.word)) parts.push(`${tagShows(second.word)}.`);
    }
    parts.push('한 곳만 말했다면 흘려들어도 되지만, 서로 다른 길로 걸어와 같은 자리를 가리킨 것이라 이 두 가지는 평생 따라다니는 결로 보셔도 됩니다.');
    out.공통 = { text: parts.join(' '), sources: first.from };
  } else {
    out.공통 = {
      text: '여러 갈래가 겹치는 자리가 없습니다. 어느 하나로 잘라 말하기 어려운 구성이라는 뜻이니, 한 가지를 정답으로 두지 마시고 상황에 따라 다른 얼굴이 나온다고 보시는 편이 맞습니다.',
      sources: [],
    };
  }

  // 한 체계의 최고·최저를 억지로 생활 조언으로 바꾸지 않는다.
  // 같은 영역을 최소 두 곳 이상이 각각 좋고 나쁘게 봐야만 '갈림'이라고 말한다.
  // 총운은 모든 항목을 섞은 값이라 특정 조언으로 번역하지 않는다.
  const voices = (block?.results ?? []).filter((x) => x.areas);
  const conflicts = AREAS
    .filter((area) => area !== '총운')
    .map((area) => {
      const plus = voices.filter((x) => (x.areas[area] ?? 50) >= 58);
      const minus = voices.filter((x) => (x.areas[area] ?? 50) <= 42);
      return { area, plus, minus };
    })
    .filter((x) => x.plus.length >= 2 && x.minus.length >= 2)
    .sort((a, b) => (b.plus.length + b.minus.length) - (a.plus.length + a.minus.length));

  if (conflicts.length) {
    const x = conflicts[0];
    const area = { 애정운: '사람 관계', 금전운: '돈', 직장운: '일과 자리', 학업운: '배움', 건강운: '몸과 생활 리듬' }[x.area];
    out.갈림 = {
      text: `${area}에 대해서는 계산 결과가 한쪽으로 모이지 않습니다. ${x.plus.length}곳은 힘이 실린다고 보고, ${x.minus.length}곳은 속도를 조절하라고 봅니다. 이 항목은 좋다·나쁘다로 단정하지 말고, 잘 풀리는 신호가 보일 때만 한 단계씩 움직이며 확인하는 편이 맞습니다.`,
      sources: [...x.plus.slice(0, 2), ...x.minus.slice(0, 2)].map((v) => v.name),
    };
  }
  return out;
}

