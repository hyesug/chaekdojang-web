const LUCKY_COLOR = [
  ['초록', '연두'], ['빨강', '분홍'], ['노랑', '베이지'], ['하양', '은색'], ['검정', '남색'],
];
const LUCKY_NUM = [[3, 8], [2, 7], [5, 10], [4, 9], [1, 6]];
const LUCKY_DIR = ['동쪽', '남쪽', '가운데', '서쪽', '북쪽'];
const LUCKY_CONSONANT = [['ㄱ', 'ㅋ'], ['ㄴ', 'ㄷ', 'ㄹ', 'ㅌ'], ['ㅇ', 'ㅎ'], ['ㅅ', 'ㅈ', 'ㅊ'], ['ㅁ', 'ㅂ', 'ㅍ']];

const top = (days, key, n) =>
  days.slice().sort((a, b) => b[key] - a[key]).slice(0, n).map((x) => x.d);
const bottom = (days, key, n) =>
  days.slice().sort((a, b) => a[key] - b[key]).slice(0, n).map((x) => x.d);

export function luckyDays(days, weakEl) {
  const avoid = days.filter((x) => x.sinsal.includes('양인')).map((x) => x.d);
  // 좋은 날을 고를 때는 양인이 든 날을 아예 뺀다. 점수가 높아도 권할 수 없다.
  const ok = days.filter((x) => !x.sinsal.includes('양인'));
  // 귀인은 천을만 본다. 월덕·천덕은 탈을 덜어주는 자리지 사람이 붙는 자리가 아니다.
  const helper = days.filter((x) => x.sinsal.includes('천을')).map((x) => x.d);
  const nums = LUCKY_NUM[weakEl];
  return {
    move: top(ok, 'score', 3),
    contract: top(ok, 'score', 3),
    money: top(ok, 'wealth', 3),
    love: top(ok, 'love', 3),
    best: top(ok, 'score', 4),
    avoid,
    worst: bottom(ok, 'score', 3),
    helper,
    color: LUCKY_COLOR[weakEl],
    num: nums,
    dir: LUCKY_DIR[weakEl],
    consonant: LUCKY_CONSONANT[weakEl],
  };
}

