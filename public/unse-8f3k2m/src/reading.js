/**
 * 한 달치 일자별 운세.
 *
 * 하루에 열다섯 체계를 다 돌린다. 30일이면 450번인데 재보니 36밀리초라
 * 아낄 이유가 없었다. 아끼면 그만큼 근거가 얇아진다.
 */
export function monthDays(input, chart, y, m) {
  const me = {
    dayStem: input.dayStem, dayBranch: input.dayBranch,
    yearBranch: input.yearBranch, monthBranch: input.monthBranch,
  };
  const last = new Date(Date.UTC(y, m, 0)).getUTCDate();
  const WD = ['일', '월', '화', '수', '목', '금', '토'];
  const out = [];

  for (let d = 1; d <= last; d++) {
    const jdn = toJDN(y, m, d);
    const gz = { stem: (jdn + 9) % 10, branch: (jdn + 1) % 12 };
    const sinsal = sinsalOf(me, gz);

    const f = forecastPeriod(input, chart, makePeriod('day', { y, m, d }));
    let score = f.areas.총운.score ?? 50;

    // 신살은 점수를 밀어준다. 양인은 크게 끌어내린다 - 힘이 넘쳐 다치는 자리다.
    for (const s of sinsal) score += (SINSAL_TONE[s] ?? 0) * (s === '양인' ? 22 : 7);
    score = Math.max(5, Math.min(95, score));

    out.push({
      d, weekday: WD[(jdn + 1) % 7], sinsal, score,
      // 같은 날엔 늘 같은 문장이 나오되, 이웃한 날끼리는 겹치지 않도록
      seed: gz.stem * 12 + gz.branch + d,
      wealth: f.areas.금전운.score ?? 50,
      love: f.areas.애정운.score ?? 50,
    });
  }

  // 순위를 매겨 등급을 붙인다. 양인은 순위와 무관하게 따로 표시한다 -
  // 힘이 넘쳐 다치는 자리라 점수가 높아도 조심해야 하는 날이다.
  const order = out.slice().sort((a, b) => b.score - a.score);
  order.forEach((x, i) => {
    const q = (i + 1) / order.length;
    const g = GRADE.find((t) => q <= t.upto);
    if (x.sinsal.includes('양인')) {
      x.grade = YANGIN_GRADE.name; x.cls = YANGIN_GRADE.cls;
    } else {
      x.grade = g.name; x.cls = g.cls;
    }
  });

  for (const x of out) {
    const key = (x.sinsal.includes('양인') ? '조심' : x.grade).replace(' ', '');
    x.line = x.sinsal.includes('양인')
      ? SINSAL_LINE.양인
      : x.sinsal.length
        ? `${pick(DAY_LINE[key], x.seed)} ${SINSAL_LINE[x.sinsal[0]]}`
        : pick(DAY_LINE[key], x.seed);
    delete x.seed;
  }
  return out;
}

