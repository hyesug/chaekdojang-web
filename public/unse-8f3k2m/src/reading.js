/**
 * @param {object} input  prepareInput 결과
 * @param {object} chart  사주 원국
 * @param {object} synth  readFortune().synthesis — 합의도를 여기서 본다
 */
export function lifeReading(input, chart, synth) {
  const gods = tenGodDistribution(chart.pillars, chart.dayStem);
  const el = elementDistribution(chart.pillars);
  const daeun = computeDaeun(chart, input.isMale, input.jdUT);
  const L = daeun.list;
  const c = certainty(synth?.consensus?.ratio);

  const strong = el.pct.indexOf(Math.max(...el.pct));
  const weak = el.pct.indexOf(Math.min(...el.pct));
  // 두 번째로 옅은 오행. 직업은 하나만 보고 정하기에는 폭이 좁다.
  const weak2 = el.pct
    .map((v, i) => ({ v, i }))
    .filter((x) => x.i !== weak)
    .sort((a, b) => a.v - b.v)[0].i;
  const b = BODY[weak];
  const dayEl = chart.pillars.day.element;

  return {
    early: stage('초년', L.slice(0, 2),
      `이 무렵에 성격의 뼈대가 잡히고, 그때 곁에 있던 사람이 오래 남습니다.${c.hedge}`),
    middle: stage('중년', L.slice(2, 5),
      '어려움과 성공을 한 차례씩 겪는데, 주관이 뚜렷해 뒤로 갈수록 자리가 단단해집니다.'),
    late: stage('말년', L.slice(5, 8),
      '앞서 모은 것이 재물이었다면 이 시기는 이름을 얻는 때가 됩니다.'),

    sibling: sibling(gods.groups.비겁),
    child: child(input.isMale ? gods.groups.관성 : gods.groups.식상),
    spouse: spouse(input.isMale ? gods.groups.재성 : gods.groups.관성, input.isMale),

    // 모자란 오행이 하나만은 아니다. 둘을 같이 채우는 쪽이 실제로 맞다.
    career:
      `사주에 ${j(ELEMENTS[strong], '이')} 가장 두텁고 ` +
      `${ELEMENTS[weak]}·${ELEMENTS[weak2]}${'의 기운이 옅습니다'}. ` +
      `이 둘을 채우는 일을 고르면 흐름도 순해지고 몸도 덜 상합니다. ` +
      `${JOB[weak]}. 또한 ${JOB[weak2]}.`,

    body:
      `회원님은 ${SEASONS[seasonOf(input.monthBranch)]}에 태어난 ` +
      `${ELEMENTS[dayEl]}(${ELEMENT_HANJA[dayEl]})의 기운입니다. ` +
      `오행 가운데 ${j(ELEMENTS[weak], '이')} 특히 모자라니 그 자리를 메우는 데 신경 쓰셔야 합니다. ` +
      `몸에서는 ${b.organ}의 기능을 각별히 살피셔야 하고, 얼굴 주변으로는 ${j(b.part, '이')} 가장 약한 자리입니다. ` +
      `${b.care}.`,

    meta: { gods, el, daeun, strong, weak, certainty: c },
  };
}

