/** 내 숙에서 상대 숙까지 세어 관계를 정한다 */
function relationFrom(nakA, nakB) {
  const p = ((nakB - nakA + 27) % 27) + 1;      // 1~27
  const idx = (p - 1) % 9;
  const name = idx === 0 ? HEADS[Math.floor((p - 1) / 9)] : NINE[idx];
  return { position: p, name, ...{ score: REL[name][0], kr: REL[name][1], text: REL[name][2] } };
}

export function compare(a, b) {
  const nA = nakshatraOf(a.jdUT).index;
  const nB = nakshatraOf(b.jdUT).index;

  const aToB = relationFrom(nA, nB);   // A가 볼 때 B는 무엇인가
  const bToA = relationFrom(nB, nA);

  const score = Math.round((aToB.score + bToA.score) / 2);
  const gap = Math.abs(aToB.score - bToA.score);

  const suA = SU[nA], suB = SU[nB];

  const facts = [
    { label: `${a.name}의 숙`, value: `${suA[0]}宿`, note: `${suA[1]}수` },
    { label: `${b.name}의 숙`, value: `${suB[0]}宿`, note: `${suB[1]}수` },
    { label: `${a.name} → ${b.name}`, value: `${aToB.name}(${aToB.kr})`, note: `${aToB.position}번째 자리` },
    { label: `${b.name} → ${a.name}`, value: `${bToA.name}(${bToA.kr})`, note: `${bToA.position}번째 자리` },
  ];

  const readings = [
    {
      title: `${j(a.name, '이')} 보는 ${b.name} — ${aToB.name}(${aToB.kr})`,
      text: aToB.text,
    },
    {
      title: `${j(b.name, '이')} 보는 ${a.name} — ${bToA.name}(${bToA.kr})`,
      text: bToA.text,
    },
  ];

  if (aToB.name === bToA.name) {
    readings.push({
      title: '양쪽이 같은 관계입니다',
      text: `드문 경우입니다. 두 사람이 서로를 같은 자리에서 보고 있어, 주고받는 것이 어느 한쪽으로 기울지 않습니다. 관계의 무게가 대등하다는 뜻이고, 그만큼 오해가 적습니다.`,
    });
  } else if (gap >= 30) {
    const giver = aToB.score < bToA.score ? a.name : b.name;
    const taker = aToB.score < bToA.score ? b.name : a.name;
    readings.push({
      title: '한쪽으로 기운 관계입니다',
      text: `${a.name}에게 ${j(b.name, '은')} ${aToB.name}, ${b.name}에게 ${j(a.name, '은')} ${bToA.name}입니다. 방향에 따라 판정이 크게 갈립니다.\n\n` +
        `숙요가 다른 궁합법과 갈리는 지점이 바로 여기입니다. 관계를 하나의 점수로 뭉뚱그리지 않고, 누가 주고 누가 받는지를 방향별로 나눠 봅니다. ` +
        `이 조합에서는 ${giver} 쪽이 더 내주고 ${taker} 쪽이 더 받는 구조입니다. 나쁘다는 뜻이 아니라, ${j(giver, '이')} 지치지 않도록 관계의 균형을 의식적으로 맞춰야 오래 간다는 뜻입니다.`,
    });
  }

  if (aToB.name === '壊' || bToA.name === '壊') {
    readings.push({
      title: '괴(壊)가 걸려 있습니다',
      text: '숙요에서 가장 조심스럽게 보는 자리입니다. 서로 맞지 않는다기보다, 한쪽이 다른 쪽의 판을 무너뜨리는 힘으로 작용한다고 봅니다. 다만 옛 문헌도 "가까이 두지 말라"까지는 말하지 않고, 중요한 결정을 함께 내리는 자리는 피하라는 정도로 씁니다. 일로 엮이는 것은 특히 신중하게 보세요.',
    });
  }

  return {
    id: meta.id, name: meta.name, score,
    weight: 1.1,
    headline: `${aToB.name}(${aToB.kr}) ↔ ${bToA.name}(${bToA.kr})`,
    facts, readings,
  };
}

// ─────────────────────────────────────────────────────────────
// 시기 운세
// ─────────────────────────────────────────────────────────────
// 그날 달이 든 숙과 본명숙 사이의 거리로 본다.
// 숙요는 원래 택일에 쓰던 체계라, 시기를 보는 것이 본령이다.

const REL_AREA = {
  命: 4, 栄: 15, 衰: -12, 安: 12, 危: -14, 成: 14, 壊: -18, 友: 8, 親: 10, 業: -4, 胎: 2,
};

export function forecast(input, chart, period) {
  const mine = nakshatraOf(input.jdUT).index;
  const now = nakshatraOf(period.jd).index;
  const p = ((now - mine + 27) % 27) + 1;
  const idx = (p - 1) % 9;
  const NINE2 = ['命', '栄', '衰', '安', '危', '成', '壊', '友', '親'];
  const HEADS2 = ['命', '業', '胎'];
  const name = idx === 0 ? HEADS2[Math.floor((p - 1) / 9)] : NINE2[idx];
  const base = REL_AREA[name] ?? 0;

  const areas = {};
  for (const a of ['총운', '애정운', '금전운', '직장운', '학업운', '건강운']) {
    areas[a] = Math.max(8, Math.min(94, Math.round(50 + base)));
  }
  if (name === '栄') areas.금전운 += 6;
  if (name === '安') areas.건강운 += 6;
  if (name === '成') areas.직장운 += 6;
  if (name === '危') areas.건강운 -= 6;

  const KR = { 命: '명', 栄: '영', 衰: '쇠', 安: '안', 危: '위', 成: '성', 壊: '괴', 友: '우', 親: '친', 業: '업', 胎: '태' };
  return {
    id: meta.id, name: meta.name, weight: 1.2,
    headline: `${name}(${KR[name]}) · ${SU[now][1]}수`,
    text: `이 시기 달이 ${SU[now][0]}宿에 듭니다. 본명숙 ${SU[mine][0]}宿에서 세어 ${p}번째, ${name}(${KR[name]})의 자리입니다. ` +
      (base > 8 ? '움직이기 좋은 때입니다.'
        : base < -8 ? '큰일을 벌이기에는 맞지 않는 때입니다.'
        : '무난하게 지나가는 때입니다.'),
    areas,
  };
}

export default { meta, analyze, compare , forecast };
