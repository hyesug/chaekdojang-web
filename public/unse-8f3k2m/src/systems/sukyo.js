  親: [82, '친', '가족 같은 자리입니다. 설명하지 않아도 통하고 서로를 보호하려 듭니다.'],
  業: [50, '업', '업으로 얽힌 자리입니다. 좋든 나쁘든 쉽게 끊어지지 않고, 헤어져도 다시 만나게 되는 인연으로 봅니다.'],
