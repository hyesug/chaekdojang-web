/** 기질 값에서 가장 두드러진 축 하나를 공통 어휘로 뽑아낸다 */
function tagFromTraits(traits) {
  const MAP = {
    주도: ['주도', null], 외향: ['사교', '내향'],
    감성: ['감수성', '분석'], 안정: ['안정', '변화'], 실리: ['재물', null],
  };
  let best = null, bestAbs = 0.45; // 이만큼은 기울어야 태그로 친다
  for (const [k, v] of Object.entries(traits)) {
    if (Math.abs(v) > bestAbs) { bestAbs = Math.abs(v); best = MAP[k][v > 0 ? 0 : 1]; }
  }
  return best ? [best] : [];
}

