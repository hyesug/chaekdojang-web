/**
 * school.js — **유파를 하나 골라 적어 둔다**
 *
 * 유파가 갈리는 자리마다 "갈립니다"로 물러서면, 갈리는 자리가 많은 주제는
 * 통째로 답이 없어진다. 자녀 성별이 그랬다 — 딸이라 적은 책과 아들이라 적은
 * 책이 둘 다 있다는 이유로 아무 말도 하지 않았다.
 *
 * 실제로 쓰이는 서비스들은 **유파를 골라 설정으로 둔다**(정자시법·고전점성술·
 * 홀사인처럼). 고르는 것이 정직하지 않은 것이 아니라, **고르고 밝히지 않는
 * 것**이 정직하지 않은 것이다.
 *
 * 그래서 여기서는 셋을 지킨다.
 *   1. **가장 널리 쓰이는 계열 하나**를 고른다
 *   2. 무엇을 골랐는지 **답에 적는다**
 *   3. 반대로 적은 계열이 있으면 **그것도 한 줄 남긴다**
 *
 * 나중에 화면에서 고를 수 있게 하려면 이 표만 바꾸면 된다.
 */

/**
 * 자녀 성별 — 여명은 식상, 남명은 관성으로 본다.
 *
 * **고른 계열**: 자평 계열의 다수설. 여명은 식신을 딸, 상관을 아들로 보고
 * 남명은 정관을 딸, 편관을 아들로 본다.
 *
 * **다른 계열**: 이를 정반대로 적은 책도 있다. 근대 이후 판본에서 특히
 * 갈리는 자리라, 맞다고 단정하지 않고 "이 계열을 쓴다"고 밝힌다.
 */
export const CHILD_GENDER = {
  school: '자평 계열 다수설',
  other: '정반대로 적은 판본도 있습니다',
  female: { 식신: '딸', 상관: '아들' },
  male: { 정관: '딸', 편관: '아들' },
};

/** 그 십성이 가리키는 성별 — 고른 계열 기준 */
export function genderOf(gender, god) {
  const table = gender === 'female' ? CHILD_GENDER.female : CHILD_GENDER.male;
  return table[god] ?? null;
}

