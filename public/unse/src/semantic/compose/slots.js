/** 제목에서 한자 괄호를 털어 견준다 */
const norm = (s) => String(s ?? '').replace(/\s*[(（][^)）]*[)）]/g, '').trim();

/**
 * 읽기 하나가 여러 칸에 걸칠 때 — **조각을 골라낸다.**
 *
 * 사화 읽기는 네 궁을 한 줄에 늘어놓는다.
 *
 *   "거문 화록 → 명궁 · 태양 화권 → 천이궁 · 문곡 화과 → 질액궁 · 문창 화기 → 자녀궁"
 *
 * 관록궁이 들었다고 이 줄을 통째로 직업 칸에 넣으면 나머지 세 궁이 딸려
 * 들어온다. 제목만 보는 필터로는 못 가른다. 그래서 `pick` 정규식을 주면
 * **그 조각만** 떼어 온다.
 *
 * 조각은 ` · ` 와 문장 끝에서 가른다 — 이 저장소 읽기가 그 두 가지로만
 * 나열하기 때문이다. 골라낸 조각이 없으면 그 칸은 이 읽기를 받지 않는다
 * (그 사람에게는 해당 궁에 아무것도 안 떨어졌다는 뜻이다).
 */
const fragments = (text) => String(text ?? '')
  .split(/\s+·\s+|(?<=[.。!?])\s+|\n+/)
  .map((s) => s.trim())
  .filter(Boolean);

/**
 * 칸을 채운다.
 *
 * @param {object} fortune `natalFortune(...).fortune`
 * @param {object[]} [structures] `readStructures(chart).structures`
 * @param {string} [domain]
 */
export function fillSlots(fortune, structures = [], domain = 'career') {
  const table = SLOTS[domain];
  if (!table) throw new Error(`모르는 갈래: ${domain}`);
  const systems = Object.values(fortune?.results ?? {});

  return table.map((slot) => {
    const filled = [];

    for (const [sysName, titleRe, opts] of slot.from) {
      const v = systems.find((x) => x.name === sysName);
      if (!v) continue;
      for (const r of v.readings ?? []) {
        if (r?.mono || !titleRe.test(norm(r.title))) continue;

        let text = r.text;
        if (opts?.pick) {
          const keep = fragments(r.text).filter((f) => opts.pick.test(f));
          // 골라낼 것이 없으면 이 사람에게는 해당 자리가 비어 있는 것이다
          if (!keep.length) continue;
          // 목록 조각("무곡 화록 → 재백궁")은 가운뎃점으로, 문장은 그냥 잇는다.
          // 섞어서 공백으로만 이으면 "→ 재백궁 탐랑 화권 → 재백궁 화록은…" 처럼
          // 어디서 끊기는지 알 수 없게 된다.
          const list = keep.filter((f) => f.includes('→'));
          const prose = keep.filter((f) => !f.includes('→'));
          const head = list.join(' · ').replace(/([^.!?])$/, '$1.');
          text = [head, prose.join(' ')].filter(Boolean).join(' ');
        }
        filled.push({
          system: sysName, what: r.title, text, kind: 'reading',
          picked: opts?.pick ? true : undefined,
        });
      }
    }
    for (const name of slot.struct) {
      const s = structures.find((x) => x.name === name);
      if (s) filled.push({ system: '사주(격)', what: s.name, text: s.text, kind: 'structure', source: s.source });
    }

    return {
      ...slot,
      filled,
      // 아무도 말하지 않는 칸은 비워 두고 비었다고 말한다.
      // 다른 칸의 말로 메우면 그 순간 근거 없는 문장이 된다.
      empty: filled.length === 0,
    };
  });
}

/**
 * 조립한 것을 사람 말로.
 *
 * **한 칸에 여럿이 들어와도 하나로 줄이지 않는다.** 둘 다 맞을 수 있고,
 * 어느 쪽이 맞는지 가릴 근거가 이 저장소에 없다(고르는 학습은 LOO 0.015 로
 * 실패했다). 대신 누가 한 말인지 붙여서 나란히 둔다.
 */
export function describeSlots(slots) {
  const out = [];
  for (const s of slots) {
    if (s.empty) {
      out.push({ label: s.label, ask: s.ask, empty: true,
        text: '이 자리를 말하는 체계가 없습니다. 비워 둡니다.' });
      continue;
    }
    out.push({
      label: s.label,
      ask: s.ask,
      empty: false,
      source: s.source,
      voices: s.filled.map((f) => ({ system: f.system, what: f.what, text: f.text })),
    });
  }
  return out;
}
