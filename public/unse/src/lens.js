/**
 * 궁합을 여덟 축으로 읽는다.
 *
 * @param {object} c        compareFortune 결과
 * @param {object} scores   축 이름 -> 점수 (reading.js 가 계산한 다섯 축)
 * @param {function} evi    축 이름 -> 근거 배열
 */
/**
 * 구간은 절대 점수가 아니라 그 쌍 안에서의 순위로 가른다.
 *
 * 처음에는 62/45 같은 절대 기준을 썼는데 '어렵다'가 한 건도 나오지 않았다.
 * 300쌍을 재보니 다섯 축 점수가 평균 61에 10%가 55, 90%가 67로 아주 좁게
 * 모여 있었다 - 열다섯을 가중평균한 값이라 가운데로 몰리는 게 당연하다.
 *
 * 분포의 30·70% 자리로 경계를 옮겨봤더니 이번에는 다른 문제가 나왔다.
 * 200쌍 가운데 131쌍에서 여덟 축이 전부 같은 구간으로 떨어졌다. 축끼리
 * 점수 차가 1점 안팎이라 한 쌍 안에서는 다 같이 오르내리기 때문이다.
 * 그러면 "이 관계는 전반적으로 무난합니다"를 여덟 번 쓰는 것과 같다.
 *
 * 읽는 사람이 알고 싶은 것은 '이 관계의 절대 점수'가 아니라 '우리는 어디가
 * 낫고 어디가 걸리는가'다. 그래서 여덟 축을 그 쌍 안에서 줄 세운다.
 * 위 셋이 hi, 아래 셋이 lo, 가운데 둘이 mid 다.
 */
const TOP_N = 3;
const BOTTOM_N = 3;

export function compatAxes(scores, evi) {
  const rows = Object.entries(AXIS_MAP).map(([key, map]) => {
    const vals = map.from.map((k) => scores[k] ?? 50);
    const v = map.pick === 'min' ? Math.min(...vals)
      : vals.reduce((a, b) => a + b, 0) / vals.length;
    return { key, map, v };
  });

  const order = [...rows].sort((a, b) => b.v - a.v);
  const bandOf = (row) => {
    const at = order.indexOf(row);
    if (at < TOP_N) return 'hi';
    if (at >= order.length - BOTTOM_N) return 'lo';
    return 'mid';
  };

  return rows.map((row) => {
    const band = bandOf(row);
    const lens = AXIS_LENS[row.key][band];
    return {
      key: row.key, label: row.map.label, note: row.map.note, band,
      conclusion: lens.c, reality: lens.r, good: lens.g, bad: lens.b,
      from: row.map.from,
      evidence: evi(row.map.from[0]),
    };
  });
}
