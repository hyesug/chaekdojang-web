/* ═══════════════════════════════════════════════════════════
   말의 세기 - 몇 개가 같은 곳을 가리키는가
   ═══════════════════════════════════════════════════════════ */

/**
 * 한 체계가 말한 것과 넷이 함께 말한 것을 같은 세기로 쓰면 안 된다.
 *
 * 예전에는 낱말이 나오면 그냥 단정해서 썼다. 그러면 한 체계에서만 나온
 * 것도 "당신은 이런 사람입니다"가 된다. 근거가 하나뿐인데 단정하는 것은
 * 근거가 없는 것보다 나쁘다 - 읽는 사람이 확인할 방법까지 막기 때문이다.
 *
 * 그래서 핵심 넷 가운데 몇이 같은 낱말을 들었는지로 세기를 정한다.
 */
/**
 * 세기에 맞춰 문장 자체를 바꾼다.
 *
 * 위에 "가능성입니다" 한 줄을 얹는 것으로는 부족하다. 본문이 여전히
 * 단정하고 있으면 읽는 사람은 본문을 읽지 머리말을 읽지 않는다.
 *
 * 결론은 어미를 바꾸고, 행동까지 좁혀 말하는 대목(현실에서는·잘 쓰면)은
 * 근거가 얇을 때 아예 내보내지 않는다. 한 갈래에서만 잡힌 신호로
 * "당신은 이런 상황에서 이렇게 움직입니다"까지 말할 수는 없다.
 */
const TAIL = {
  strong: (core) => `${core}입니다.`,
  mid: (core) => `${core}에 가깝습니다.`,
  weak: (core) => `${core}일 수 있습니다.`,
  faint: (core) => `${core}인지 참고해볼 만합니다.`,
};

/** 결론에서 어미를 떼어 낱말 덩이만 남긴다 */
const coreOf = (conclusion) => conclusion.replace(/입니다\.?$/, '');

/** 행동까지 좁혀 말해도 되는 세기인가 */
export const canDetail = (level) => level === 'strong' || level === 'mid';

export function strengthOf(coreCount, totalCount) {
  const text = coreCount > 0
    ? `핵심 4체계 중 ${coreCount}개 · 전체 ${totalCount}개 체계에서 같은 특징을 짚었습니다.`
    : `보조 체계 ${totalCount}개에서만 같은 특징을 짚었습니다.`;

  if (coreCount >= 3) return { level: 'strong', text };
  if (coreCount === 2) return { level: 'mid', text };
  if (coreCount === 1) return { level: 'weak', text };
  return { level: 'faint', text };
}

/**
 * 성향 리딩 - 명반에서 낱말을 뽑아 네 칸으로 펼친다.
 *
 * 낱말 자체는 각 체계가 이미 붙여 둔 것이다(tags). 여기서는 그 낱말을
 * 문장으로 바꾸지 않고, 낱말마다 마련된 렌즈 네 칸을 그대로 쓴다.
 * 그래서 같은 낱말이면 같은 렌즈가 나오지만, 어떤 낱말이 몇 개 체계에서
 * 나왔느냐가 사람마다 달라 세기와 차례가 달라진다.
 *
 * @param {object} r  readFortune 결과
 * @param {number} n  몇 개까지 보여줄 것인가
 */
export function traitLenses(r, n = 4) {
  const s = r.synthesis;
  const all = [...(s.sharedTags ?? []), ...(s.soloTags ?? [])];

  const rows = [];
  for (const t of all) {
    const lens = TAG_LENS[t.word];
    if (!lens) continue;
    const from = t.from ?? [];
    const core = from.filter((name) => CORE_NAMES.includes(name));
    const st = strengthOf(core.length, from.length);
    rows.push({
      word: t.word,
      coreCount: core.length,
      total: from.length,
      from,
      ...st,
      ...lens,
      // 결론은 세기에 맞춰 어미를 바꾼다
      conclusion: (TAIL[st.level] ?? TAIL.weak)(coreOf(lens.conclusion)),
      // 근거가 얇으면 행동까지 좁혀 말하지 않는다
      detail: canDetail(st.level),
      evidence: from.map((name) => {
        const sys = r.results.find((x) => x.name === name);
        return sys ? {
          name,
          core: CORE_NAMES.includes(name),
          headline: sys.headline,
          facts: sys.facts.slice(0, 2).map((x) => `${x.label} ${x.value}`),
        } : { name, core: false, headline: '', facts: [] };
      }),
    });
  }

  // 핵심 체계가 많이 든 낱말부터. 같으면 전체 수로 가른다.
  rows.sort((a, b) => b.coreCount - a.coreCount || b.total - a.total);
  return rows.slice(0, n);
}

