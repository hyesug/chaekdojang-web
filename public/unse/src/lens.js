/**
 * lens.js - 명반만 보고 쓰는 리딩
 *
 * 이 파일이 지키려는 규칙은 하나다.
 *
 *   "이 사람의 직업도, 연애 상황도, 재정 상태도, 과거에 무슨 말을 했는지도
 *    전혀 모르는 채로, 명반 데이터만 보고 이 문장을 쓸 수 있는가?"
 *
 * 답이 '아니오'면 그 문장은 여기 들어올 수 없다. 예전 문장에는 "돈이 적어도
 * 인정받는 자리를 택하고", "기술·기획·분석·문서 일이 잘 맞습니다" 같은 것이
 * 있었다. 읽으면 그럴듯하지만, 명반에서 나온 것이 아니라 사람을 알고 쓴
 * 것처럼 보인다. 실제로는 아무도 모르고 쓴 것이라 더 나쁘다.
 *
 * 그래서 구체성의 기준을 바꿨다.
 *   좋은 구체성 - 의사결정 방식, 갈등 방식, 반복되는 상황, 잘 되는 조건,
 *                무너지는 조건
 *   나쁜 구체성 - 직업명, 업종, 금액, 병명, 특정 사건
 *
 * 문단 구조도 통일한다. 결론 하나로 끝내면 "그래서 어쩌라고"가 남는다.
 *   결론      - 명반에서 확인되는 패턴
 *   현실에서는 - 그 패턴이 생활에서 어떤 모양으로 나타나는가
 *   장점      - 잘 작동할 때
 *   주의할 점 - 같은 구조가 과해졌을 때
 *   근거      - 어느 체계의 무슨 값에서 나왔는가 (본문 뒤로 보낸다)
 */

