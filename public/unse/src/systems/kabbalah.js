export function analyze(input) {
  // 개인년은 양력 1월 1일에 바뀐다. 입춘 기준 해를 쓰면 1월생 화면에서
  // 개인년이 한 해 뒤처진다.
  const { year, month, day, civilYear } = input;
  const currentYear = civilYear;

  const digitSum = String(year).split('').reduce((a, c) => a + Number(c), 0) + month + day;
  const lifePath = digitRoot(digitSum);
  const sephira = SEPHIROT[lifePath] ?? SEPHIROT[digitRoot(lifePath, false)];

  const birthday = digitRoot(day);
  const personalYear = digitRoot(month + day + currentYear, false);

  const facts = [
    { label: '라이프 패스', value: String(lifePath), note: `${sephira.name} · ${sephira.mean}` },
    { label: '세피라', value: sephira.hebrew,
      note: `${sephira.name} · 라이프 패스 수를 세피라에 잇는 것은 현대 수비학 쪽 대응이지 전통 카발라의 고정 산법이 아니다` },
    { label: '생일수', value: String(birthday), note: '타고난 재능의 결' },
    { label: `${currentYear} 개인년`, value: String(personalYear), note: '9년 주기 안의 위치' },
    { label: '원소', value: sephira.element, note: '오행 환산 시 근사 적용' },
    // 물어보는 사람이 가장 헷갈리는 자리라 계산하지 않았다는 것을 값으로 낸다.
    // 비워 두면 "안 적혀 있으니 알아서 채워도 되겠지"가 된다.
    { label: '22경로 (נתיבות)', value: '미구현',
      note: '세피라 열 개를 잇는 22경로는 계산하지 않는다. 히브리 문자·타로 대응이 '
        + '황금새벽회 계열과 전통 카발라 계열에서 서로 다르고, 이 저장소에 어느 쪽을 '
        + '고를 근거가 없다. 근거 없이 한쪽을 고르면 계산을 자처하는 창작이 된다' },
  ];

  const readings = [
    { title: `${sephira.name} — 라이프 패스 ${lifePath}`, text: sephira.text },
    {
      title: '이 풀이가 무엇이고 무엇이 아닌가',
      text: '여기서 쓰는 것은 **생년월일 수비학(라이프 패스·생일수·개인년)** 이고, '
        + '그 수를 세피라 하나에 잇는 것은 현대 수비학 쪽 대응입니다. '
        + '**생명나무의 22경로를 짚는 전통 카발라 계산이 아닙니다** — 그쪽은 계산하지 '
        + '않습니다. 경로 대응은 유파마다 갈리는데 어느 쪽을 고를 근거가 없어서, '
        + '있는 척하기보다 없다고 적습니다.',
    },
    {
      title: `${currentYear}년은 개인년 ${personalYear}`,
      text: PERSONAL_YEAR[personalYear],
    },
    {
      title: `생일수 ${birthday}`,
      text: `태어난 날(${day}일)에서 나오는 수입니다. 라이프 패스가 걸어갈 길이라면 생일수는 그 길을 걷는 데 이미 쥐고 있는 도구에 가깝습니다. ` +
        SEPHIROT[birthday]?.keywords.join('·') + ' 쪽의 재능이 기본값으로 깔려 있습니다.',
    },
  ];

  return result({
    id: meta.id,
    name: meta.name,
    hanja: meta.hanja,
    headline: `라이프 패스 ${lifePath} · ${sephira.name} · ${currentYear}년 개인년 ${personalYear}`,
    facts,
    readings,
    signals: {
      elements: WESTERN_TO_OHAENG[sephira.element] ?? [0, 0, 0, 0, 0],
      traits: sephira.traits,
      domains: {
        재물: personalYear === 8 ? 72 : personalYear === 4 ? 60 : null,
        관계: personalYear === 2 || personalYear === 6 ? 68 : null,
        직업: personalYear === 1 || personalYear === 8 ? 70 : null,
        건강: null,
        학업: personalYear === 7 ? 72 : null,
      },
      tags: sephira.tags,
      keywords: sephira.keywords,
    },
  });
}

