export function compare(a, b) {
  const lp = (x) => digitRoot(String(x.year).split('').reduce((s, c) => s + Number(c), 0) + x.month + x.day);
  const lpA = lp(a), lpB = lp(b);
  const rA = lpA > 9 ? digitRoot(lpA, false) : lpA;
  const rB = lpB > 9 ? digitRoot(lpB, false) : lpB;
  const key = [rA, rB].sort((x, y) => x - y).join('-');
  const [score, text] = NUM_MATCH[key] ?? [65, '두 수가 특별한 관계를 이루지는 않습니다.'];

  const master = [lpA, lpB].filter((n) => n > 9);
  const sephA = SEPHIROT[lpA] ?? SEPHIROT[rA];
  const sephB = SEPHIROT[lpB] ?? SEPHIROT[rB];

  const readings = [
    { title: `라이프 패스 ${lpA} × ${lpB}`, text },
    {
      title: '생명나무에서의 자리',
      text: `${j(a.name, '은')} ${sephA.name}, ${j(b.name, '은')} ${sephB.name}에서 출발했습니다. ` +
        (sephA.name === sephB.name
          ? '같은 세피라라 세상을 보는 방식이 거의 같습니다. 편한 만큼 서로의 사각지대도 겹칩니다.'
          : `${j(sephA.mean, '과')} ${j(sephB.mean, '이')} 만나는 조합입니다. 서로 다른 자리에서 왔기 때문에 상대에게서 자기에게 없는 것을 봅니다.`),
    },
  ];
  if (master.length) {
    readings.push({
      title: '마스터 수가 섞여 있습니다',
      text: `${j(master.join('과 '), '은')} 줄이지 않고 그대로 보는 마스터 수입니다. 감각이 예민하고 요구하는 것이 많은 수라, 관계에서도 보통의 기준으로 재기 어렵습니다. 잘 맞으면 아주 깊게 가고, 어긋나면 스스로를 소진시키는 쪽으로 흐릅니다.`,
    });
  }

  return {
    id: meta.id, name: meta.name, score,
    weight: 0.8,
    headline: `라이프 패스 ${lpA} × ${lpB}`,
    facts: [
      { label: '라이프 패스', value: `${lpA} / ${lpB}`, note: `${sephA.name} / ${sephB.name}` },
      { label: '조합', value: key, note: '수비학 상성표' },
    ],
    readings,
  };
}

